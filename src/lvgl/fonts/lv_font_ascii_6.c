const struct ascii6_glyph_s *ascii6_dsc(uint32_t cp)
{
    for (int i = 0; g_ascii6[i].cp != 0; i++)
        if (g_ascii6[i].cp == cp)
            return &g_ascii6[i];
    return NULL;
}

const uint8_t *ascii6_bitmap(uint32_t cp)
{
    const struct ascii6_glyph_s *d = ascii6_dsc(cp);

    return d != NULL ? &g_ascii6_bitmap_pool[d->offset] : NULL;
}
